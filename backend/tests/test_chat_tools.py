async def test_get_glucose_analytics_reports_real_readings(db_and_user):
    db, user, ts_session_factory = db_and_user
    now = datetime.now(timezone.utc)
    async with ts_session_factory() as ts:
        ts.add(GlucoseReadingModel(id=uuid.uuid4(), user_id=user.id, value_mgdl=120, recorded_at=now, source="MANUAL"))
        ts.add(GlucoseReadingModel(id=uuid.uuid4(), user_id=user.id, value_mgdl=160, recorded_at=now, source="MANUAL"))
        await ts.commit()

    result = await execute_tool("get_glucose_analytics", {"days": 7}, db, user)

    assert result["has_data"] is True
    assert result["average_mgdl"] == 140.0
    assert result["reading_count"] == 2


