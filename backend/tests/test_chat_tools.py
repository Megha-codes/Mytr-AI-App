# ── Structural safety guarantee ──────────────────────────────────────────

def test_no_dosing_or_medication_tool_exists_at_all():
    """The core structural guarantee, independent of the system prompt:
    there is no tool the model could call that would ever return an
    insulin dose or medication amount. Not "the tool refuses" — the tool
    doesn't exist."""
    names = {schema["function"]["name"] for schema in TOOL_SCHEMAS}
    for forbidden in ("dose", "dosage", "insulin", "medication", "medicine"):
        assert not any(forbidden in name.lower() for name in names), (
            f"found a tool name containing {forbidden!r}: {names}"
        )


async def test_unknown_tool_name_is_a_soft_error_not_a_crash(db_and_user):
    db, user, _ts = db_and_user
    result = await execute_tool("compute_insulin_dose", {}, db, user)
    assert "error" in result


