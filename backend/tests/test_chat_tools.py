async def test_get_daily_nutrition_reflects_a_logged_meal(db_and_user):
    db, user, _ts = db_and_user

    # daily_nutrition_totals reads via raw SQL (services/nutrition/
    # meals_today.py — JSONB has no sqlite compiler, same as elsewhere in
    # this app), which on sqlite expects a dashed UUID string; the ORM
    # write path log_meal goes through stores the hex form instead (its
    # bind processor's own convention). The two are consistent with each
    # other on real Postgres (native uuid comparison doesn't care about
    # formatting) but not on sqlite, so this test seeds the meal directly
    # in the representation the raw-SQL reader expects, rather than
    # chaining through log_meal first — see
    # tests/test_dashboard_activity_zero_fill.py for the same pattern.
    await db.execute(
        text("""
            INSERT INTO meal_logs (id, user_id, meal_time, food_items, total_calories, total_carbs_g)
            VALUES (:id, :user_id, :meal_time, :food_items, :calories, :carbs_g)
        """),
        {
            "id": str(uuid.uuid4()), "user_id": str(user.id), "meal_time": datetime.now(timezone.utc),
            "food_items": json.dumps([{"name": "banana"}]), "calories": 90, "carbs_g": 22.0,
        },
    )
    await db.commit()

    result = await execute_tool("get_daily_nutrition", {}, db, user)
    assert result["meal_count"] == 1
    assert result["consumed_kcal"] == 90
